    val shortBadge: String
) {
    ENGLISH("en", "English", "EN"),
    BENGALI("bn", "বাংলা", "বাং"),
    HINDI("hi", "हिन्दी", "हि"),
    ARABIC("ar", "العربية", "ع"),
    INDONESIAN("id", "Bahasa Indonesia", "ID"),
    SPANISH("es", "Español", "ES");

